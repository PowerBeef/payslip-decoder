// usage: node tests/analyze.mjs <payslip.pdf> [en|fr]  (keep payslips outside the repo)
import * as pdfjs from '../node_modules/pdfjs-dist/legacy/build/pdf.mjs';
import fs from 'fs';
import '../src/parser.js'; import '../src/agreement.js'; import '../src/analyze.js';
const PD = globalThis.PD;
PD.PACKS = JSON.parse(fs.readFileSync(new URL('../packs.enc.json', import.meta.url), 'utf8'));
const { pages } = await PD.extractPages(pdfjs, new Uint8Array(fs.readFileSync(process.argv[2])));
const parsedP = PD.parsePayslip(pages);
const t0 = Date.now(); const ag = await PD.unlockFor(parsedP.header); console.log('unlock', !!ag, (Date.now() - t0) + 'ms');
const A = PD.analyze(parsedP);
const nf = (v,d=2)=> (v==null?'—':Number(v).toFixed(d));
const L = { lang: process.argv[3]||'en', money: (v)=>'$'+nf(v), num:(v)=>String(v), pct:(v,d=1)=>nf(v,d)+'%', date:(s)=>s, kind:(k)=>k };
console.log('meta', A.meta.P, A.meta.year, 'hoursPaid', A.hoursPaid, 'worked', A.hoursWorked, 'mainRate', A.mainRate);
console.log('split', A.split.map(s=>s.id+':'+s.amount).join(' '));
console.log('splitYtd', A.splitYtd.map(s=>s.id+':'+s.amount).join(' '));
console.log('ledger', A.ledger.map(l=>l.kind+':'+l.amount+'→'+l.after).join(' | '));
console.log('recon', JSON.stringify(A.recon));
console.log('labelMap', JSON.stringify(A.labelMap), 'trunc', A.truncated);
console.log('ytdByCat', JSON.stringify(A.ytdByCat));
console.log('taxes', A.taxes.map(t=>`${t.kind} ${t.amount} ytd ${t.ytd} max ${t.annualMax} pct ${t.maxPct&&t.maxPct.toFixed(3)} exp ${t.expected}`).join('\n'));
console.log('dedGroups', A.dedGroups.map(g=>g.title+' pretax='+g.pretax+' '+g.rows.map(r=>r.kind).join(',')).join(' / '));
console.log('employer', A.employer.map(e=>e.kind+':'+e.amount).join(' '), 'claims', JSON.stringify(A.claims), JSON.stringify(A.claimInfo));
console.log('\nCHECKS', JSON.stringify(A.checkStats));
for (const c of A.checks) console.log(`[${c.status}] ${c.group} ${c.title(L)}\n      ${c.detail(L)}`);
console.log('\nCODES', JSON.stringify(A.codes.map(c=>[c.code,c.current,c.curHours,c.ytdHours,c.avgRegRate,c.cats.join('/')])));
console.log('GROUPS', JSON.stringify(A.codeGroups));
console.log('TIMELINE', JSON.stringify(A.codeTimeline));
console.log('T4', JSON.stringify(A.slips.t4)); console.log('RL1', JSON.stringify(A.slips.rl1));
console.log('retro', A.earnings.filter(e=>e.retro).length);
